readonly MODULE_NAME="Example"
readonly MODULE_DESCRIPTION="Example module description"
readonly MODULE_VERSION="0.1.0"

# During its execution, SysWatch generates a file named 
# `modules.conf` in the `config` directory. This file contains 
# one line per module in the format `module name=interval|order|remote`, 
# initially drawing values from the following three variables. 
# This `modules.conf` file takes precedence.
# for example: 
# 
# CPU=60|4| (CPU module, 60-second interval, order value 4, no remote host) 
# Disk=300|20|Raspberry1 (Disk module, 300-second interval, order value 20, display in SysWatch running on the remote host Raspberry1)
# The modules.conf file can be edited to change these values 
# without needing to modify each module individually.
#
# module execution interval in seconds
MODULE_INTERVAL=${MODULE_INTERVAL:-300}
#
# The order of appearance on the board for the card(s) generated by this module. 
# The numbers do not need to be consecutive. If a module has a value of 5 and 
# there are no modules with values of 0, 1, 2, 3, or 4, it will be the first to 
# appear. If another module has a value of 20 and there are no modules with values 
# between 6 and 19, it will be the second. It is not an error that consecutive values 
# are not required.
MODULE_ORDER=${MODULE_ORDER:-10}
# The cards are arranged on the dashboard as follows: first those with CRITICAL status,
# then those with WARNING, then those with INFO, and finally those with OK.
# Within each status group, they are sorted by the MODULE_ORDER value.
# The html auto-updates every 1 minute
#
# Hostname of the remote computer where this card will be displayed, in addition 
# to the current machine. Remote hosts must be defined in the REMOTES variable in the 
# .env file, comma separated.
# SysWatch will create a directory for each remote host within the `remote` directory.
MODULE_REMOTE=${MODULE_REMOTE:-""}
# Communication between hosts takes place via shared directories using any 
# valid method (NFS, SMB, etc.). The receiving host must share the `import` 
# directory, and the sending host must mount this shared resource with write 
# permissions to the `remote/{remote_hostname}` directory.


