example_collect() {

    # Collect raw metrics here.
    # This step should not determine the module status.

    EXAMPLE_VALUE=0
    EXAMPLE_VALUE2="$(command --parameter1 --parameter2)"
    EXAMPLE_VALUE3=$(jq -r '.user.name' "${CACHE_DIR}/data.json")

    # The cache directory stores temporary files or files that can be reused.
    # 
    # Some useful functions for working with the cache are:
    #
    # sw_cache_copy "/path/to/archive" (copy the archive to the cache directory)
    # sw_cache_post "name" "url" "data" (download a file from "url" using curl by sending JSON via the
    #                                    POST method, saving it in the cache directory as "name" and using the --data "data" flag)
    # sw_cache_download "name" "url" (downloads a file from "url" using curl, saving it in the cache directory as "name")
    # sw_cache_exists "file" (checks if "file" exists in the cache directory)
    # sw_cache_is_expired "file" "age" (checks if "file" is older than a given date)
    # sw_cache_read "file" (reads the content of "file")
    # sw_cache_remove "file" (delete "file")
    #
    # Cached files can be used for data collection.

}

example_analyze() {

    # Regardless of the visual configuration of the widgets, the module status is generally 
    # determined by analyzing the collected values and changing the *_STATUS variable.

    EXAMPLE_STATUS="${SW_STATUS_OK}"

    if (( EXAMPLE_VALUE >= EXAMPLE_CRITICAL )); then

        EXAMPLE_STATUS="${SW_STATUS_CRITICAL}"

    elif (( EXAMPLE_VALUE >= EXAMPLE_WARNING )); then

        EXAMPLE_STATUS="${SW_STATUS_WARNING}"

    fi

}

example_update_state() {

    sw_state_set "module_version" "${MODULE_VERSION}"

    # -------------------------------------------------------------------------
    # Module metadata (consumed by lib/html.sh)
    # -------------------------------------------------------------------------

    # The sw_state_set command stores a value in memory, which 
    # will be saved to the .state file when sw_state_save is executed. 
    # It is used as follows: sw_state_set "key" "value"
    sw_state_set "module.label" "$(sw_translate "Example")"
    # The icon must be an SVG and located in `html/icons/{dir}`
    # for example, `lucide/box` must be at `html/icons/lucide/box.svg`.
    sw_state_set "module.icon" "lucide/box"
    sw_state_set "module.order" "$MODULE_ORDER"

    # -------------------------------------------------------------------------
    # Data
    # -------------------------------------------------------------------------

    sw_state_set "value" "${EXAMPLE_VALUE}"

    # Each key in the .state file can have modifiers that 
    # change its behavior. In the following case, label, order, 
    # widget, and unit are modifiers.

    sw_state_set "value.label" "$(sw_translate "Value")"
    sw_state_set "value.widget" "line"
    sw_state_set "value.unit" "%"
    sw_state_set "value.order" "10"
    

    # If no widget is specified, a text label will be used. 
    # The available widgets are line, gauge, and image.

    # The available modifiers are: 
    #
    # label      (changes the label; otherwise, the key is used)
    # unit       (adds the unit: %, kph, etc.)
    # align      (aligns the text: left, center, right)
    # color      (text color: white, black, yellow, pink, red, green, orange)
    # warning    (combined with widget=gauge; minimum value for the status to become WARNING)
    # critical   (combined with widget=gauge; minimum value for the status to become CRITICAL)
    # scale      (for widget=line: dynamic scale—min and max can vary; zero—min 0 and variable max; 
    #             fixed—preset min and max)
    # order      (sorting within the card)
    # hidden     (hidden data)
    # from and id (used for messages from other modules)
    # module_version, status, status_since, and timestamp (automatically added by SysWatch).

    sw_state_set "value2" "$EXAMPLE_VALUE2"
    sw_state_set "value2.widget" "gauge"
    sw_state_set "value2.unit" "%"
    sw_state_set "value2.order" "70"
    sw_state_set "value2.warning" "80"
    sw_state_set "value2.critical" "95"

    sw_state_set "image" "picture.jpg" # picture.jpg (or whatever the image is) must be located in html/images.
    sw_state_set "image.label" "$(sw_translate "Photo of the day")"
    sw_state_set "image.widget" "image"
    sw_state_set "image.order" "10"

    # sw_translate is a command that translates the provided text.
    # The global variable SW_TRANSLATIONS_LANG (in .env) defines the language 
    # (en, es, fr, ...). The command looks for the entry in the 
    # translations/{lang}.conf file (e.g., es.conf, fr.conf); if found,
    # it returns the translation, and if not, it adds it as a blank entry, 
    # and the user can type the translation.
    # The file format is: 
    #
    # en=There are no active alerts. 
    # es=No hay alertas activas.
    sw_state_set "value3" "$(sw_translate "There are no active alerts.")"
    sw_state_set "value3.label" "$(sw_translate "Detail")"
    sw_state_set "value3.color" "green"
    sw_state_set "value3.order" "40"
    
    sw_state_set "value4" "$(sw_translate "Hidden data.")"
    sw_state_set "value4.label" "$(sw_translate "Detail")"
    sw_state_set "value4.order" "50"
    sw_state_set "value4.hidden" "true"

    # Other useful functions for working with .state files and their content
    # 
    # sw_state_delete_key "key" (deletes the "key" entry and its value)
    # value="$(sw_state_get "key")"  (returns the value associated with key)
    # sw_state_delete (delete the .state file; it must run without using sw_state_load and sw_state_save and after 
    #                  performing sw_state_use, otherwise, the saving process might recreate it)
    # sw_state_clear (clears the entire contents of the array holding the .state data, after performing sw_state_load)
    

    # Communication between modules is handled by the function pair `sw_message_send` 
    # and `sw_message_load`. `sw_message_send` writes data to a `.state` 
    # file that is subsequently loaded and used by another module. 
    # `sw_message_load` loads a message written by another module into the 
    # current module's own `.state` file. The format for `sw_message_send` is: 
    # 
    # `sw_message_send "target_state" "data" "persistence (true/false)" "identifier"`. 
    #
    # Data is written to the `.state` file as follows: 
    #
    # message_from_module_count=10
    # message_from_module_count.from=example
    # message_from_module_count.hidden=true
    # message_from_module_count.persist=true
    #
    # `sw_message_load` takes a single parameter: `identifier`.
    #
    # value=$(sw_message_load "count") #$value=10
    #
    # If `persist` is `false`, the data is deleted from the `state` file.

    # Regardless of the visual configuration of the widgets, the module status is generally 
    # determined by analyzing the collected values and changing the *_STATUS variable.
}

example_report() {

    sw_log_info \
        "${MODULE_NAME}" \
        "Example value: ${EXAMPLE_VALUE} (${EXAMPLE_STATUS})"

}

sw_module_run() {

    # The following command checks whether the 
    # necessary programs are available on the system.
    #
    # sw_require_command jq
    # sw_require_command curl
    # sw_require_command ...

    # Configuration variables are located in .env; however, it is 
    # possible to load other configuration variables stored in .conf files 
    # located in the config directory. In this case, config/example.conf is loaded.
    #
    # sw_module_load_config "example"

    # Each module saves its data to a .state file within 
    # the state directory. SysWatch then uses the values from 
    # the file to generate the corresponding card on the dashboard. 
    # The following command defines the filename.
    sw_state_use "example"

    # SysWatch can export .state files, timers, and .csv files to a SysWatch 
    # instance on another host; if the $MODULE_REMOTE variable is defined in the 
    # module or in the modules.conf file, the following 
    # command will do this.
    if [[ -n "$MODULE_REMOTE" ]]; then
        sw_state_remote "$MODULE_REMOTE"
    fi

    # The following command loads the values
    # from the .state file into memory.
    sw_state_load

    example_collect

    example_analyze

    # The following command sets the status of the record based 
    # on the analysis of the collected values. The possible statuses are: 
    # OK, WARNING, CRITICAL, INFO, UNKNOWN.
    sw_status_update "${EXAMPLE_STATUS}" || return 1

    example_update_state

    #The following command saves the data to the .state file.
    sw_state_save

    example_report

    # Optional: append to CSV history for sparkline widgets.
    #
    # When defining a "line" type widget, it is strictly necessary to 
    # have a CSV file containing stored (integer) values 
    # derived from data collection. These CSV files are stored in subdirectories 
    # within the `csv` directory; for instance, if the `.state` file is 
    # named `example` and the key within it is named `value`, SysWatch will 
    # look for the file `csv/example/value.csv`.
    #
    # sw_csv_append \
    #     "example" \
    #     "value" \
    #     "${EXAMPLE_VALUE}"
    #
    # Other functions for working with CSVs:
    #
    # sw_csv_last "example" "value"  (retrieves the last value saved in the CSV)
    # sw_csv_last_values "example" "value" "8"  (retrieves the last 8 values saved in the CSV)
    # sw_csv_last_max "example" "value" "4" (retrieves the 4 highest values stored in the CSV)
    #
    # The CSV format is always: timestamp,value. CSVs can be used to store any data 
    # that needs to be saved, even if it won't be used by a line widget.
    

    # Communication between modules is handled by the function pair `sw_message_send` 
    # and `sw_message_load`. `sw_message_send` writes data to a `.state` 
    # file that is subsequently loaded and used by another module. 
    # `sw_message_load` loads a message written by another module into the 
    # current module's own `.state` file. The format for `sw_message_send` is: 
    # 
    # `sw_message_send "target_state" "data" "persistence (true/false)" "identifier"`. 
    #
    # Data is written to the `.state` file as follows: 
    #
    # message_from_module_count=10
    # message_from_module_count.from=example
    # message_from_module_count.hidden=true
    # message_from_module_count.persist=true
    #
    # `sw_message_load` takes a single parameter: `identifier`.
    #
    # sw_message_send "example2" "10" "true" "count"

    # You can create timers—actions triggered after a specific number of 
    # SysWatch executions. If a timer is set with a value of 5, 
    # this refers to 5 executions of `syswatch_user.sh`, not 5 minutes or seconds; 
    # if `syswatch_user.sh` runs every 2 minutes, the total duration is 10 minutes. 
    # The `sw_timer_create` command initializes the timer using the format: 
    #
    # sw_timer_create ".state file" "total count" "action"
    # Valid actions are `statusok`, `statusinfo`, `statuswarning`, `statuscritical`, and `deletestate`.
    #
    # sw_timer_create "example" "10" "statusok"
    #
    # This changes the status in the example.state file to OK after 10 executions of SysWatch.



}
