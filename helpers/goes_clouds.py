# Infrared: cloud-top temperature (°C) -> overlay colour. Warmer than the
# first stop is fully transparent, because in IR a warm cloud is
# indistinguishable from the ground.
COLD_STOPS = [
    # (degrees below zero, (R, G, B, A))
    (10, (230, 235, 240, 0)),
    (30, (230, 235, 240, 110)),
    (40, (180, 220, 255, 150)),
    (50, (255, 222, 0, 185)),
    (60, (255, 120, 0, 210)),
    (70, (230, 0, 0, 230)),
    (80, (200, 0, 200, 240)),
]

# Visible: the sun must be at least this high (degrees) for the band to be
# used at all, and fully trusted above the second value.
VIS_SUN_MIN = 10.0
VIS_SUN_FULL = 25.0

# Visible: reflectance (corrected for sun angle) below VIS_CLEAR is ground
# (transparent); above VIS_FULL it is a fully opaque cloud.
VIS_CLEAR = 0.15
VIS_FULL = 0.65
VIS_ALPHA = 215
VIS_COLOR = (245, 248, 252)

# Interpolation used to enlarge the visible image (0.5 km pixels) to the
# map size: 1 = bilinear (blocky edges), 3 = cubic (smoother edges).
VIS_RESAMPLE_ORDER = 3

# Visible only fills in where the infrared is blind: it is fully used where
# the pixel is warmer than VIS_IR_BLIND below zero, and fully ignored where
# it is colder than VIS_IR_SURE below zero (the infrared already sees it).
VIS_IR_BLIND = 10
VIS_IR_SURE = 30


