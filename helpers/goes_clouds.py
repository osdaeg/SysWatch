def sample_brightness_temperature(nc_path, bounds, size):
    """
    Returns brightness temperature in Kelvin on the output grid
    (NaN where unavailable).
    """

    grid_x, grid_y = mercator_grid(bounds, size)

    with Dataset(nc_path) as ds:
        projection = ds.variables["goes_imager_projection"]

        h = float(projection.perspective_point_height)

        geos = geos_crs(
            h,
            float(projection.longitude_of_projection_origin),
            projection.sweep_angle_axis,
            float(projection.semi_major_axis),
            float(projection.semi_minor_axis),
        )

        # Scan angles (radians) -> metres on the satellite's projection.
        x_axis = np.asarray(ds.variables["x"][:], dtype="float64") * h
        y_axis = np.asarray(ds.variables["y"][:], dtype="float64") * h

        rows, cols = pixel_indices(
            grid_x,
            grid_y,
            geos,
            x_axis,
            y_axis,
        )

        row_lo, row_hi, col_lo, col_hi = window_limits(
            rows,
            cols,
            len(y_axis),
            len(x_axis),
        )

        # Only the small window we need is read from disk.
        window = ds.variables["CMI"][row_lo:row_hi, col_lo:col_hi]

        window = np.ma.filled(
            window.astype("float32"),
            np.nan,
        )

    return resample(window, rows, cols, row_lo, col_lo)


