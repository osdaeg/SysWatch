def colorize_ir(kelvin):
    """
    Converts brightness temperature to an RGBA overlay.
    """

    cold = 273.15 - kelvin          # degrees below 0 °C

    xp = [stop[0] for stop in COLD_STOPS]

    channels = []

    for index in range(4):
        fp = [stop[1][index] for stop in COLD_STOPS]

        channels.append(
            np.interp(cold, xp, fp, left=0, right=fp[-1])
        )

    rgba = np.stack(channels, axis=-1)

    # No data -> transparent.
    rgba[~np.isfinite(kelvin)] = 0

    return Image.fromarray(
        np.clip(rgba, 0, 255).astype("uint8"),
        "RGBA",
    )


def colorize_visible(reflectance, kelvin, sun_deg, day_weight):
    """
    White overlay whose opacity follows how much light each pixel reflects,
    but only where the infrared cannot see the cloud (warm pixels).
    """

    albedo = reflectance / math.sin(math.radians(sun_deg))

    amount = np.clip(
        (albedo - VIS_CLEAR) / (VIS_FULL - VIS_CLEAR),
        0.0,
        1.0,
    )

    amount = amount * amount * (3.0 - 2.0 * amount)

    # 1 where the infrared is blind, 0 where it already sees the cloud.
    cold = 273.15 - kelvin

    blind = 1.0 - np.clip(
        (cold - VIS_IR_BLIND) / (VIS_IR_SURE - VIS_IR_BLIND),
        0.0,
        1.0,
    )

    blind = np.where(np.isfinite(cold), blind, 1.0)

    alpha = np.nan_to_num(
        amount * blind * VIS_ALPHA * day_weight,
        nan=0.0,
    )

    rgba = np.empty(reflectance.shape + (4,), dtype="uint8")

    rgba[..., 0] = VIS_COLOR[0]
    rgba[..., 1] = VIS_COLOR[1]
    rgba[..., 2] = VIS_COLOR[2]
    rgba[..., 3] = np.clip(alpha, 0, 255).astype("uint8")

    return Image.fromarray(rgba, "RGBA")


