def mercator_grid(bounds, size):
    """
    Pixel centres of the output image, in Web Mercator metres.
    """

    width, height = size

    south, west, north, east = bounds

    to_mercator = Transformer.from_crs(
        "EPSG:4326",
        "EPSG:3857",
        always_xy=True,
    )

    x_min, y_min = to_mercator.transform(west, south)
    x_max, y_max = to_mercator.transform(east, north)

    xs = x_min + (np.arange(width) + 0.5) / width * (x_max - x_min)
    ys = y_max - (np.arange(height) + 0.5) / height * (y_max - y_min)

    return np.meshgrid(xs, ys)


def geos_crs(h, lon0, sweep, a, b):
    return CRS.from_proj4(
        f"+proj=geos +h={h} +lon_0={lon0} +sweep={sweep} "
        f"+a={a} +b={b} +units=m +no_defs"
    )


def pixel_indices(grid_x, grid_y, geos, x_axis, y_axis):
    """
    Maps the output grid to fractional (row, col) indices of the
    satellite image. `x_axis` / `y_axis` are in projection metres.
    """

    to_geos = Transformer.from_crs(
        "EPSG:3857",
        geos,
        always_xy=True,
    )

    gx, gy = to_geos.transform(grid_x, grid_y)

    # The axes are regular grids: metres -> fractional pixel index.
    dx = (x_axis[-1] - x_axis[0]) / (len(x_axis) - 1)
    dy = (y_axis[-1] - y_axis[0]) / (len(y_axis) - 1)

    cols = (gx - x_axis[0]) / dx
    rows = (gy - y_axis[0]) / dy

    if not np.isfinite(cols).all() or not np.isfinite(rows).all():
        raise RuntimeError(
            "El área solicitada queda fuera del disco del satélite."
        )

    return rows, cols


def window_limits(rows, cols, n_rows, n_cols):
    row_lo = max(0, int(np.floor(rows.min())) - 2)
    row_hi = min(n_rows, int(np.ceil(rows.max())) + 3)

    col_lo = max(0, int(np.floor(cols.min())) - 2)
    col_hi = min(n_cols, int(np.ceil(cols.max())) + 3)

    if row_hi <= row_lo or col_hi <= col_lo:
        raise RuntimeError(
            "El área solicitada queda fuera de la imagen del satélite."
        )

    return row_lo, row_hi, col_lo, col_hi


def resample(window, rows, cols, row_lo, col_lo, order=1):
    coords = [rows - row_lo, cols - col_lo]

    if order <= 1:
        return map_coordinates(
            window,
            coords,
            order=1,
            mode="nearest",
            cval=np.nan,
        )

    # Spline interpolation spreads a single NaN over the whole window,
    # so fill the gaps first and blank them out again afterwards.
    missing = ~np.isfinite(window)

    if missing.any():
        fill = 0.0 if missing.all() else np.nanmedian(window)

        window = np.where(missing, fill, window)

    result = map_coordinates(
        window,
        coords,
        order=order,
        mode="nearest",
    )

    if missing.any():
        gap = map_coordinates(
            missing.astype("float32"),
            coords,
            order=1,
            mode="nearest",
        )

        result[gap > 0] = np.nan

    return result


