def calculate_bounds(center_lat, center_lon, width_km, height_km):
    """
    Same calculation as aircraft-radar: (south, west, north, east).
    """

    earth_radius_km = 6371.0088

    lat_delta = math.degrees(
        (height_km / 2.0) / earth_radius_km
    )

    lon_delta = math.degrees(
        (width_km / 2.0) /
        (earth_radius_km * math.cos(math.radians(center_lat)))
    )

    return (
        center_lat - lat_delta,
        center_lon - lon_delta,
        center_lat + lat_delta,
        center_lon + lon_delta,
    )


def sun_elevation(lat, lon, when):
    """
    Solar elevation in degrees (NOAA approximation, `when` in UTC).
    """

    when = when.astimezone(dt.timezone.utc)

    hour = when.hour + when.minute / 60.0 + when.second / 3600.0

    gamma = (
        2.0 * math.pi / 365.0
        * (when.timetuple().tm_yday - 1 + (hour - 12.0) / 24.0)
    )

    eqtime = 229.18 * (
        0.000075
        + 0.001868 * math.cos(gamma)
        - 0.032077 * math.sin(gamma)
        - 0.014615 * math.cos(2 * gamma)
        - 0.040849 * math.sin(2 * gamma)
    )

    declination = (
        0.006918
        - 0.399912 * math.cos(gamma)
        + 0.070257 * math.sin(gamma)
        - 0.006758 * math.cos(2 * gamma)
        + 0.000907 * math.sin(2 * gamma)
        - 0.002697 * math.cos(3 * gamma)
        + 0.00148 * math.sin(3 * gamma)
    )

    solar_minutes = hour * 60.0 + eqtime + 4.0 * lon

    hour_angle = math.radians(solar_minutes / 4.0 - 180.0)

    lat_rad = math.radians(lat)

    cos_zenith = (
        math.sin(lat_rad) * math.sin(declination)
        + math.cos(lat_rad) * math.cos(declination)
        * math.cos(hour_angle)
    )

    cos_zenith = max(-1.0, min(1.0, cos_zenith))

    return 90.0 - math.degrees(math.acos(cos_zenith))


def smoothstep(value):
    value = min(1.0, max(0.0, value))

    return value * value * (3.0 - 2.0 * value)


