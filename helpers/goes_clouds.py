def find_basemap(candidates):
    for path in candidates:
        if os.path.isfile(path):
            return path

    raise RuntimeError(
        "No existe el mapa base: " + " ni ".join(candidates)
    )


def daytime_basemap(gray, day_weight):
    """
    Cross-fades from the grayscale map to the original one as the sun
    rises, so visible clouds (white) have something to contrast with.
    Falls back to the grayscale map if the original is missing.
    """

    try:
        path = find_basemap(BASEMAP_COLOR_CANDIDATES)

    except RuntimeError as exc:
        print(f"Aviso: {exc}; se mantiene el mapa gris.", file=sys.stderr)
        return gray

    print(f"Mapa base de día: {path}")

    with Image.open(path) as image:
        color = image.convert("RGBA")

    if color.size != gray.size:
        color = color.resize(gray.size, Image.Resampling.LANCZOS)

    return Image.blend(gray, color, day_weight)


def build_cloud_map(nc_path, scan):
    basemap = find_basemap(BASEMAP_GRAY_CANDIDATES)
    print(f"Mapa base: {basemap}")

    with Image.open(basemap) as image:
        base = image.convert("RGBA")

    bounds = calculate_bounds(
        WEATHER_LAT,
        WEATHER_LON,
        WIDTH_KM,
        HEIGHT_KM,
    )

    # The full-disk scan takes ~10 minutes; use its middle.
    sun = sun_elevation(
        WEATHER_LAT,
        WEATHER_LON,
        scan + dt.timedelta(minutes=5),
    )

    day_weight = smoothstep(
        (sun - VIS_SUN_MIN) / (VIS_SUN_FULL - VIS_SUN_MIN)
    )

    print(f"Sol: {sun:.1f}° de elevación")

    kelvin = sample_brightness_temperature(
        nc_path,
        bounds,
        base.size,
    )

    valid = kelvin[np.isfinite(kelvin)]

    if valid.size:
        print(
            f"Temperatura de brillo: "
            f"min {valid.min() - 273.15:.1f} °C | "
            f"max {valid.max() - 273.15:.1f} °C"
        )

    visible = None

    if USE_VISIBLE and day_weight > 0:
        try:
            key = find_visible_key(scan)

            reflectance = sample_reflectance(key, bounds, base.size)

            visible = colorize_visible(
                reflectance,
                kelvin,
                sun,
                day_weight,
            )

            valid = reflectance[np.isfinite(reflectance)]

            if valid.size:
                print(
                    f"Reflectancia visible: "
                    f"min {valid.min():.2f} | max {valid.max():.2f}"
                )

        except Exception as exc:
            print(
                f"Aviso: no se pudo usar la banda visible ({exc}); "
                f"se usa solo infrarrojo.",
                file=sys.stderr,
            )

    elif USE_VISIBLE:
        print("De noche: solo infrarrojo.")

    # Visible fills the gaps; infrared goes on top and always wins.
    if visible is not None:
        base = daytime_basemap(base, day_weight)

        base.alpha_composite(visible)

    base.alpha_composite(colorize_ir(kelvin))

