def _attr(node, name, default=None):
    value = node.attrs.get(name, default)

    if isinstance(value, np.ndarray):
        value = value.ravel()[0] if value.size else default

    if isinstance(value, bytes):
        value = value.decode()

    return value


def read_scaled(dataset, index=Ellipsis):
    """
    Reads (part of) a NetCDF variable through h5py and applies what
    netCDF4 would do automatically: unsigned, fill value, scale, offset.
    """

    raw = dataset[index]

    unsigned = str(_attr(dataset, "_Unsigned", "false")).lower() == "true"

    if unsigned:
        raw = raw.view(np.dtype(f"u{raw.dtype.itemsize}"))

    data = raw.astype("float64")

    data = (
        data * float(_attr(dataset, "scale_factor", 1.0))
        + float(_attr(dataset, "add_offset", 0.0))
    )

    fill = _attr(dataset, "_FillValue")

    if fill is not None:
        fill = np.array(fill).astype(dataset.dtype)

        if unsigned:
            fill = fill.view(raw.dtype)

        data[raw == fill] = np.nan

    return data


def sample_reflectance(key, bounds, size):
    """
    Returns visible reflectance factor on the output grid, reading only
    the part of the remote file that covers the area.
    """

    import aiohttp
    import fsspec
    import h5py

    grid_x, grid_y = mercator_grid(bounds, size)

    url = f"{BASE_URL}/{key}"

    fs = fsspec.filesystem(
        "http",
        client_kwargs={"timeout": aiohttp.ClientTimeout(total=90)},
    )

    with fs.open(
        url,
        mode="rb",
        block_size=HTTP_BLOCK,
        cache_type="blockcache",
    ) as remote:

        with h5py.File(remote, "r") as ds:
            projection = ds["goes_imager_projection"]

            h = float(_attr(projection, "perspective_point_height"))

            geos = geos_crs(
                h,
                float(_attr(projection, "longitude_of_projection_origin")),
                _attr(projection, "sweep_angle_axis"),
                float(_attr(projection, "semi_major_axis")),
                float(_attr(projection, "semi_minor_axis")),
            )

            x_axis = read_scaled(ds["x"]) * h
            y_axis = read_scaled(ds["y"]) * h

            rows, cols = pixel_indices(
                grid_x,
                grid_y,
                geos,
                x_axis,
                y_axis,
            )

            row_lo, row_hi, col_lo, col_hi = window_limits(
                rows,
                cols,
                len(y_axis),
                len(x_axis),
            )

            window = read_scaled(
                ds["CMI"],
                (slice(row_lo, row_hi), slice(col_lo, col_hi)),
            ).astype("float32")

        fetched = getattr(remote.cache, "total_requested_bytes", None)

    if fetched:
        print(f"Banda visible: {fetched / 1e6:.1f} MB descargados")

    result = resample(
        window,
        rows,
        cols,
        row_lo,
        col_lo,
        order=VIS_RESAMPLE_ORDER,
    )

    # Cubic interpolation can overshoot slightly at sharp edges.
    return np.clip(result, 0.0, 2.0)


