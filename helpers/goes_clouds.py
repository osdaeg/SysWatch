def list_keys(prefix):
    url = (
        f"{BASE_URL}/?"
        + urllib.parse.urlencode(
            {"list-type": "2", "prefix": prefix}
        )
    )

    with urllib.request.urlopen(url, timeout=30) as response:
        root = ET.fromstring(response.read())

    return [
        element.text
        for element in root.iter()
        if element.tag.endswith("Key")
    ]


def hour_prefix(moment):
    return (
        f"{PRODUCT}/"
        f"{moment.year}/"
        f"{moment.timetuple().tm_yday:03d}/"
        f"{moment.hour:02d}/"
    )


def find_latest_key(band):
    """
    Looks in the current UTC hour and the previous ones.
    """

    now = dt.datetime.now(dt.timezone.utc)
    needle = f"C{band:02d}_{SATELLITE_TAG}"

    for back in range(HOURS_BACK + 1):
        moment = now - dt.timedelta(hours=back)

        keys = sorted(
            key for key in list_keys(hour_prefix(moment))
            if needle in key
        )

        if keys:
            return keys[-1]

    raise RuntimeError(
        f"No se encontró ningún archivo GOES reciente (banda {band})."
    )


def find_visible_key(when):
    """
    Finds the visible-band file of the same scan as the infrared one.
    """

    needle = f"C{BAND_VIS:02d}_{SATELLITE_TAG}"

    keys = [
        key for key in list_keys(hour_prefix(when))
        if needle in key
    ]

    if not keys:
        raise RuntimeError(
            f"No hay archivo de la banda {BAND_VIS} para esa hora."
        )

    best = min(
        keys,
        key=lambda key: abs((scan_time(key) - when).total_seconds()),
    )

    gap = abs((scan_time(best) - when).total_seconds())

    if gap > MAX_SCAN_DIFF_MIN * 60:
        raise RuntimeError(
            f"La banda {BAND_VIS} más cercana está a "
            f"{int(gap // 60)} min del infrarrojo."
        )

    return best


def scan_time(key):
    """
    Parses the scan start time from the file name (sYYYYDDDHHMMSSt).
    """

    stamp = key.split("_s")[1][:13]

    return dt.datetime.strptime(
        stamp, "%Y%j%H%M%S"
    ).replace(tzinfo=dt.timezone.utc)


def download(key):
    os.makedirs(GOES_CACHE, exist_ok=True)

    path = os.path.join(GOES_CACHE, os.path.basename(key))

    if os.path.isfile(path) and os.path.getsize(path) > 0:
        print(f"Archivo en caché: {os.path.basename(key)}")
        return path

    url = f"{BASE_URL}/{key}"

    print(f"Descargando {os.path.basename(key)}")

    temp = path + ".tmp"

    try:
        with urllib.request.urlopen(url, timeout=120) as response:
            with open(temp, "wb") as file:
                while True:
                    chunk = response.read(1 << 20)

                    if not chunk:
                        break

                    file.write(chunk)

        os.replace(temp, path)

    finally:
        if os.path.exists(temp):
            os.remove(temp)

    return path


def clean_old_downloads():
    limit = time.time() - KEEP_HOURS * 3600

    if not os.path.isdir(GOES_CACHE):
        return

    for name in os.listdir(GOES_CACHE):
        path = os.path.join(GOES_CACHE, name)

        if os.path.isfile(path) and os.path.getmtime(path) < limit:
            os.remove(path)


