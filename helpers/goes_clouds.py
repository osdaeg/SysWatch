#!/usr/bin/env python3

"""
GOES cloud overlay helper (day + night).

Downloads the latest GOES-East full-disk imagery from the public NOAA
bucket on AWS, reprojects it to Web Mercator over exactly the same
geographic area as the cached aircraft-radar base map, and overlays it.

  - Infrared (ABI band 13): cloud-top temperature. Works day and night,
    but low clouds and fog are invisible (they look like the ground).
  - Visible (ABI band 2, red): daytime only. Shows low clouds and fog.
    Only the pixels inside the map area are fetched (HTTP range requests),
    not the whole 0.5 km full-disk file.

The infrared is always the main source. The visible band is used only by
day and only where the infrared cannot tell whether there is cloud (warm
pixels); wherever the infrared already sees cold cloud tops, it wins. If
the visible band cannot be read for any reason, the script falls back to
infrared only.

The base map is owned/generated by aircraft-radar.
This helper only adds the cloud layer.

Requires: numpy, scipy, pyproj, netCDF4, Pillow, h5py, fsspec, aiohttp
  sudo apt install python3-numpy python3-scipy python3-pyproj \
                   python3-netcdf4 python3-pil python3-h5py \
                   python3-fsspec python3-aiohttp

Environment (same as the RainViewer helper):
  WEATHER_LAT, WEATHER_LON, CACHE_DIR, HTML_DIR
Optional:
  AIRCRAFT_MAP_WIDTH_KM, AIRCRAFT_MAP_HEIGHT_KM   (default 100)
  GOES_VISIBLE=0                                  (infrared only)
"""

