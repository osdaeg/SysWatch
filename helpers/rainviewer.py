#!/usr/bin/env python3

"""
RainViewer radar overlay helper.

Downloads the latest RainViewer radar tiles for the configured
geographic area and overlays them on the cached aircraft-radar
base map.

The base map is owned/generated by aircraft-radar.
This helper only adds the radar layer.
"""

import io
import json
import math
import os
import sys
import urllib.request

from PIL import Image


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

WEATHER_LAT = float(os.environ["WEATHER_LAT"])
WEATHER_LON = float(os.environ["WEATHER_LON"])

WIDTH_KM = 100
HEIGHT_KM = 100

BASEMAP_FILE = os.path.join(
    os.environ["CACHE_DIR"],
    f"aircraft_map_base_"
    f"{os.environ['WEATHER_LAT']}_"
    f"{os.environ['WEATHER_LON']}.png",
)

RADAR_FILE = os.path.join(
    os.environ["HTML_DIR"],
    "images/radar.png",
)

RAINVIEWER_API = (
    "https://api.rainviewer.com/public/weather-maps.json"
)

RAINVIEWER_TILE_CACHE = os.path.join(
    os.environ["CACHE_DIR"],
    "rainviewer",
)

os.makedirs(
    RAINVIEWER_TILE_CACHE,
    exist_ok=True,
)

RAINVIEWER_ZOOM = 7
TILE_SIZE = 512


# ---------------------------------------------------------------------------
# Geographic helpers
# ---------------------------------------------------------------------------

def calculate_bounds(center_lat, center_lon, width_km, height_km):
    """
    Calculates an approximate geographic bounding box centered
    on the configured location.
    """

    earth_radius_km = 6371.0088

    half_width = width_km / 2.0
    half_height = height_km / 2.0

    lat_delta = math.degrees(
        half_height / earth_radius_km
    )

    lon_delta = math.degrees(
        half_width /
        (
            earth_radius_km *
            math.cos(math.radians(center_lat))
        )
    )

    return (
        center_lat - lat_delta,
        center_lon - lon_delta,
        center_lat + lat_delta,
        center_lon + lon_delta,
    )


def latlon_to_world(lat, lon, zoom):
    """
    Converts latitude/longitude to global Web Mercator
    pixel coordinates.
    """

    lat = max(
        min(lat, 85.05112878),
        -85.05112878,
    )

    scale = TILE_SIZE * (2 ** zoom)

    x = (
        (lon + 180.0) /
        360.0 *
        scale
    )

    lat_rad = math.radians(lat)

    y = (
        1.0 -
        math.asinh(math.tan(lat_rad)) / math.pi
    ) / 2.0 * scale

    return x, y


# ---------------------------------------------------------------------------
# RainViewer API
# ---------------------------------------------------------------------------

def get_latest_radar():
    """
    Returns RainViewer host and latest radar frame path.
    """

    with urllib.request.urlopen(
        RAINVIEWER_API,
        timeout=20,
    ) as response:

        data = json.load(response)

    past = data.get("radar", {}).get("past", [])

    if not past:
        raise RuntimeError(
            "RainViewer no devolvió frames de radar."
        )

    frame = past[-1]

    host = data["host"]
    path = frame["path"]
    timestamp = frame["time"]

    print(f"RainViewer frame: {timestamp}")
    print(f"RainViewer path:  {path}")

    return host, path, timestamp


# ---------------------------------------------------------------------------
# Tile helpers
# ---------------------------------------------------------------------------

def required_tiles(bounds, zoom):
    """
    Returns all XYZ tiles intersecting the requested bounds.
    """

    south, west, north, east = bounds

    x1, y1 = latlon_to_world(
        north,
        west,
        zoom,
    )

    x2, y2 = latlon_to_world(
        south,
        east,
        zoom,
    )

    tile_x1 = int(x1 // TILE_SIZE)
    tile_y1 = int(y1 // TILE_SIZE)

    tile_x2 = int(x2 // TILE_SIZE)
    tile_y2 = int(y2 // TILE_SIZE)

    tiles = []

    for y in range(tile_y1, tile_y2 + 1):
        for x in range(tile_x1, tile_x2 + 1):
            tiles.append(
                (zoom, x, y)
            )

    return tiles

def download_tile(host, path, z, x, y):
    url = (
        f"{host}{path}/"
        f"{TILE_SIZE}/"
        f"{z}/{x}/{y}/"
        f"2/1_1.png"
    )

   # url = (
 #       f"{host}{path}/"
#        f"512/7/"
 #       f"{WEATHER_LAT}/{WEATHER_LON}/"
 #       f"2/1_1.png"
#    )

    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            data = response.read()

        cache_file = os.path.join(
            RAINVIEWER_TILE_CACHE,
            f"{z}_{x}_{y}.png",
        )

        with open(cache_file, "wb") as file:
            file.write(data)

        image = Image.open(
            io.BytesIO(data)
        ).convert("RGBA")

        alpha = image.getchannel("A")

        if alpha.getbbox():
            print(f"  {z}/{x}/{y}: CON ECO")
        else:
            print(f"  {z}/{x}/{y}: vacío")

        return image

    except Exception as error:
        print(
            f"Error descargando tile "
            f"{z}/{x}/{y}: {error}",
            file=sys.stderr,
        )
        return None

# ---------------------------------------------------------------------------
# Radar layer
# ---------------------------------------------------------------------------

def build_radar_layer(
    bounds,
    host,
    path,
):
    """
    Builds a transparent radar image covering exactly
    the requested geographic bounds.
    """

    tiles = required_tiles(
        bounds,
        RAINVIEWER_ZOOM,
    )

    print(f"Radar tiles: {len(tiles)}")

    if not tiles:
        raise RuntimeError(
            "No se encontraron tiles de RainViewer."
        )

    tile_xs = [
        x for _, x, _ in tiles
    ]

    tile_ys = [
        y for _, _, y in tiles
    ]

    min_x = min(tile_xs)
    max_x = max(tile_xs)

    min_y = min(tile_ys)
    max_y = max(tile_ys)

    canvas_width = (
        max_x - min_x + 1
    ) * TILE_SIZE

    canvas_height = (
        max_y - min_y + 1
    ) * TILE_SIZE

    canvas = Image.new(
        "RGBA",
        (
            canvas_width,
            canvas_height,
        ),
        (0, 0, 0, 0),
    )

    for z, x, y in tiles:

        tile = download_tile(
            host,
            path,
            z,
            x,
            y,
        )

        px = (
            x - min_x
        ) * TILE_SIZE

        py = (
            y - min_y
        ) * TILE_SIZE

        canvas.alpha_composite(
            tile,
            (
                px,
                py,
            ),
        )

    # Geographic bounds in global pixels.
    world_min_x, world_max_y = latlon_to_world(
        bounds[0],
        bounds[1],
        RAINVIEWER_ZOOM,
    )

    world_max_x, world_min_y = latlon_to_world(
        bounds[2],
        bounds[3],
        RAINVIEWER_ZOOM,
    )

    origin_x = min_x * TILE_SIZE
    origin_y = min_y * TILE_SIZE

    crop_left = int(
        world_min_x - origin_x
    )

    crop_top = int(
        world_min_y - origin_y
    )

    crop_right = int(
        world_max_x - origin_x
    )

    crop_bottom = int(
        world_max_y - origin_y
    )

    crop_left = max(
        0,
        crop_left,
    )

    crop_top = max(
        0,
        crop_top,
    )

    crop_right = min(
        canvas.width,
        crop_right,
    )

    crop_bottom = min(
        canvas.height,
        crop_bottom,
    )

    return canvas.crop(
        (
            crop_left,
            crop_top,
            crop_right,
            crop_bottom,
        )
    )


# ---------------------------------------------------------------------------
# Composite
# ---------------------------------------------------------------------------

def build_radar_map():
    """
    Builds the final radar-over-map image.
    """

    if not os.path.isfile(BASEMAP_FILE):
        raise RuntimeError(
            f"No existe el mapa base: "
            f"{BASEMAP_FILE}"
        )

    bounds = calculate_bounds(
        WEATHER_LAT,
        WEATHER_LON,
        WIDTH_KM,
        HEIGHT_KM,
    )

    print(
        f"Área: {WIDTH_KM} x {HEIGHT_KM} km | "
        f"centro: "
        f"{WEATHER_LAT}, {WEATHER_LON}"
    )

    host, path, timestamp = (
        get_latest_radar()
    )

    print(
        f"Radar RainViewer: "
        f"{timestamp}"
    )

    radar = build_radar_layer(
        bounds,
        host,
        path,
    )

    with Image.open(BASEMAP_FILE) as image:
        base = image.convert("RGBA")

    # The radar and base map represent exactly the same
    # geographic area. Resize only to account for the
    # different RainViewer zoom level.
    radar = radar.resize(
        base.size,
        Image.Resampling.LANCZOS,
    )

    base.alpha_composite(radar)

    base.save(
        RADAR_FILE,
        "PNG",
        optimize=True,
    )

    print(
        f"Mapa radar generado: "
        f"{RADAR_FILE}"
    )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

if __name__ == "__main__":

    try:
        build_radar_map()

    except KeyboardInterrupt:
        sys.exit(130)

    except Exception as exc:
        print(
            f"ERROR: {exc}",
            file=sys.stderr,
        )
        sys.exit(1)